#!/usr/bin/env bash
set -Eeuo pipefail

# Initial installer for a fresh Ubuntu VPS. Run as root:
#   sudo bash v2/install-ubuntu.sh

APP_NAME="petrodactal"
APP_USER="petrodactal"
APP_GROUP="petrodactal"
DB_NAME="petrodactal"
DB_USER="petrodactal"
PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
VENV_DIR="$PROJECT_DIR/.venv"
ENV_FILE="$PROJECT_DIR/.env"
SERVICE_FILE="/etc/systemd/system/petrodactal.service"
NGINX_SITE="/etc/nginx/sites-available/petrodactal-monitor"

log() { printf '\n\033[1;36m[Petrodactal] %s\033[0m\n' "$1"; }
fail() { printf '\nERROR: %s\n' "$1" >&2; exit 1; }

if [[ "$(id -u)" -ne 0 ]]; then
    fail "Please run this installer as root: sudo bash v2/install-ubuntu.sh"
fi

if [[ ! -f "$PROJECT_DIR/manage.py" || ! -f "$PROJECT_DIR/requirements.txt" ]]; then
    fail "Run this script from the v2 folder in the Petrodactal repository."
fi
case "$PROJECT_DIR" in
    /opt/*) ;;
    *) fail "For the service account to access the files safely, clone the repository under /opt (for example /opt/petrodactal-monitor).";;
esac

if [[ ! -r /etc/os-release ]]; then
    fail "Cannot identify this operating system."
fi
. /etc/os-release
if [[ "${ID:-}" != "ubuntu" ]]; then
    fail "This installer currently supports Ubuntu only."
fi

log "Installing system packages"
export DEBIAN_FRONTEND=noninteractive
apt-get update
apt-get install -y \
    build-essential \
    ca-certificates \
    curl \
    git \
    libpq-dev \
    nginx \
    openssl \
    certbot \
    python3-certbot-nginx \
    postgresql \
    postgresql-contrib \
    python3 \
    python3-dev \
    python3-pip \
    python3-venv

systemctl enable --now postgresql

log "Creating the dedicated application account"
if ! id "$APP_USER" >/dev/null 2>&1; then
    useradd --system --create-home --home-dir "/var/lib/$APP_USER" \
        --shell /usr/sbin/nologin "$APP_USER"
fi

log "Preparing the Python environment"
python3 -m venv "$VENV_DIR"
"$VENV_DIR/bin/python" -m pip install --upgrade pip
"$VENV_DIR/bin/pip" install -r "$PROJECT_DIR/requirements.txt"

SITE_HOST="_"
if [[ ! -f "$ENV_FILE" ]]; then
    printf '\n'
    read -r -p "Public hostname or IP address for this installation: " SITE_HOST_INPUT
    [[ -n "${SITE_HOST_INPUT:-}" ]] || fail "A hostname or public IP is required. You can use the VPS IP address."
    if [[ ! "$SITE_HOST_INPUT" =~ ^[A-Za-z0-9.-]+$ ]]; then
        fail "Use a simple hostname or IP address without a protocol or path."
    fi
    SITE_HOST="$SITE_HOST_INPUT"

    DB_PASSWORD="$(openssl rand -hex 24)"
    DJANGO_SECRET_KEY="$(openssl rand -hex 48)"
    ENCRYPTION_KEY="$("$VENV_DIR/bin/python" -c 'from cryptography.fernet import Fernet; print(Fernet.generate_key().decode())')"
    ALLOWED_HOSTS="localhost,127.0.0.1"
    if [[ "$SITE_HOST" != "_" ]]; then
        ALLOWED_HOSTS="$ALLOWED_HOSTS,$SITE_HOST"
    fi

    umask 077
    cat > "$ENV_FILE" <<EOF
# Generated by install-ubuntu.sh. Keep this file private and backed up.
DJANGO_SECRET_KEY=$DJANGO_SECRET_KEY
ENCRYPTION_KEY=$ENCRYPTION_KEY
DJANGO_DEBUG=false
DJANGO_ALLOWED_HOSTS=$ALLOWED_HOSTS

DB_NAME=$DB_NAME
DB_USER=$DB_USER
DB_PASSWORD=$DB_PASSWORD
DB_HOST=127.0.0.1
DB_PORT=5432

MONITORING_INTERVAL=300
EOF
    chmod 600 "$ENV_FILE"
else
    log "Existing .env found; preserving it"
    DB_PASSWORD="$(sed -n 's/^DB_PASSWORD=//p' "$ENV_FILE" | tail -n 1)"
    [[ -n "$DB_PASSWORD" ]] || fail "Existing .env has no DB_PASSWORD. Add one before rerunning."
    [[ "$DB_PASSWORD" =~ ^[A-Za-z0-9]+$ ]] || fail "DB_PASSWORD in .env must contain only letters and numbers for safe automated database setup."
    SITE_HOST="$(awk -F= '/^DJANGO_ALLOWED_HOSTS=/{split($2, hosts, ","); if (length(hosts) >= 3) print hosts[3]}' "$ENV_FILE")"
    SITE_HOST="${SITE_HOST:-_}"
fi

if [[ ! "$SITE_HOST" =~ ^[A-Za-z0-9._-]+$ ]]; then
    fail "The hostname in .env is invalid. Use a hostname or IP address only."
fi

"$VENV_DIR/bin/python" - "$ENV_FILE" <<'PY'
import sys
from dotenv import dotenv_values
from cryptography.fernet import Fernet

values = dotenv_values(sys.argv[1])
secret = values.get("DJANGO_SECRET_KEY") or ""
key = values.get("ENCRYPTION_KEY") or ""
if len(secret) < 50:
    raise SystemExit("DJANGO_SECRET_KEY in .env must contain at least 50 characters.")
try:
    Fernet(key.encode("ascii"))
except (ValueError, UnicodeEncodeError):
    raise SystemExit("ENCRYPTION_KEY in .env must be a valid Fernet key.")
for name in ("DB_NAME", "DB_USER", "DB_PASSWORD"):
    if not values.get(name):
        raise SystemExit(f"{name} must be set in .env.")
PY

log "Creating the PostgreSQL database and account"
# The generated password contains only hexadecimal characters, making it
# safe to insert into this SQL statement.
if runuser -u postgres -- psql -tAc "SELECT 1 FROM pg_roles WHERE rolname='$DB_USER'" | grep -q 1; then
    runuser -u postgres -- psql -v ON_ERROR_STOP=1 -c "ALTER ROLE $DB_USER WITH LOGIN PASSWORD '$DB_PASSWORD';"
else
    runuser -u postgres -- psql -v ON_ERROR_STOP=1 -c "CREATE ROLE $DB_USER LOGIN PASSWORD '$DB_PASSWORD';"
fi
if ! runuser -u postgres -- psql -tAc "SELECT 1 FROM pg_database WHERE datname='$DB_NAME'" | grep -q 1; then
    runuser -u postgres -- createdb --owner="$DB_USER" "$DB_NAME"
else
    runuser -u postgres -- psql -v ON_ERROR_STOP=1 -c "ALTER DATABASE $DB_NAME OWNER TO $DB_USER;"
fi

log "Preparing database tables"
cd "$PROJECT_DIR"
# This early-development installer generates the initial migrations from the
# current models. Once migrations are committed to Git, this remains harmless.
"$VENV_DIR/bin/python" manage.py makemigrations panels communities servers monitoring notifications
"$VENV_DIR/bin/python" manage.py migrate --noinput
"$VENV_DIR/bin/python" manage.py collectstatic --noinput

log "Creating the Django administrator"
if ! "$VENV_DIR/bin/python" manage.py shell -c "from django.contrib.auth import get_user_model; raise SystemExit(0 if get_user_model().objects.filter(is_superuser=True).exists() else 1)"; then
    "$VENV_DIR/bin/python" manage.py createsuperuser
else
    log "An administrator account already exists; leaving it unchanged"
fi

log "Configuring the Gunicorn systemd service"
chown -R "$APP_USER:$APP_GROUP" "$PROJECT_DIR"
chmod 600 "$ENV_FILE"
cat > "$SERVICE_FILE" <<EOF
[Unit]
Description=Petrodactal Monitor v2 web application
After=network.target postgresql.service
Requires=postgresql.service

[Service]
Type=simple
User=$APP_USER
Group=$APP_GROUP
WorkingDirectory=$PROJECT_DIR
EnvironmentFile=$ENV_FILE
ExecStart=$VENV_DIR/bin/gunicorn config.wsgi:application --bind 127.0.0.1:8000 --workers 2 --threads 2 --timeout 60 --access-logfile -
Restart=on-failure
RestartSec=5
NoNewPrivileges=true
PrivateTmp=true

[Install]
WantedBy=multi-user.target
EOF

log "Configuring Nginx"
cat > "$NGINX_SITE" <<EOF
server {
    listen 80;
    server_name $SITE_HOST;

    client_max_body_size 10m;

    location /static/ {
        alias $PROJECT_DIR/staticfiles/;
        expires 7d;
        add_header Cache-Control "public";
    }

    location / {
        proxy_pass http://127.0.0.1:8000;
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
    }
}
EOF

ln -sfn "$NGINX_SITE" /etc/nginx/sites-enabled/petrodactal-monitor
# If the user chose a raw IP address, disable Ubuntu's stock default page
# so the IP opens this application. For a named domain, leave other sites alone.
if [[ "$SITE_HOST" =~ ^[0-9.]+$ ]] && [[ -L /etc/nginx/sites-enabled/default ]]; then
    rm /etc/nginx/sites-enabled/default
fi

nginx -t
systemctl daemon-reload
systemctl enable --now postgresql
systemctl enable --now petrodactal
systemctl enable --now nginx
systemctl restart petrodactal
systemctl reload nginx

log "Installation finished"
printf 'Project directory: %s\n' "$PROJECT_DIR"
printf 'Admin page:        http://%s/admin/\n' "$SITE_HOST"
printf 'Health check:      http://%s/health/\n' "$SITE_HOST"
printf '\nUseful commands:\n'
printf '  sudo systemctl status petrodactal\n'
printf '  sudo journalctl -u petrodactal -f\n'
printf '  sudo systemctl restart petrodactal\n'
printf '\nIMPORTANT: Configure HTTPS before using real administrator credentials or panel API keys.\n'
printf 'Back up %s and the PostgreSQL database. Never lose ENCRYPTION_KEY.\n' "$ENV_FILE"
